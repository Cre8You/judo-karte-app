import datetime


def build_rehabilitation_plan_prompt(
    patient_id: str,
    joint: str,
    side: str,
    disease_name: str,
    onset_date: datetime.date,
    rehab_start_date: datetime.date,
    rest_nrs: object,
    movement_nrs: object,
    night_nrs: object,
    pain_location: str,
    pain_trigger: str,
    pain_quality: str,
    rom_summary: str,
    mmt_summary: str,
    sensory_summary: str,
    special_summary: str,
    participation: str,
    clinical_note: str,
) -> str:
    """Build the prompt used only for rehabilitation plan document text."""
    patient_id_for_prompt = patient_id or "未入力"

    return f"""あなたは臨床経験豊富な柔道整復師です。
以下の入力データだけを使用し、リハビリテーション計画書へ転記する文章を作成してください。

入力データ:
・患者ID：{patient_id_for_prompt}
・対象関節・部位：{joint}
・左右：{side}
・傷病名：{disease_name}
・発症日：{onset_date.strftime('%Y年%m月%d日')}
・リハ開始日：{rehab_start_date.strftime('%Y年%m月%d日')}
・安静時NRS：{rest_nrs}
・動作時NRS：{movement_nrs}
・夜間痛NRS：{night_nrs}
・疼痛部位：{pain_location or '未入力'}
・疼痛を誘発する動作：{pain_trigger or '未入力'}
・疼痛の性質：{pain_quality or '未入力'}
・ROM評価とROM制限因子：
{rom_summary}
・MMT評価：
{mmt_summary}
・感覚検査：
{sensory_summary}
・スペシャルテスト：
{special_summary}
・生活上の困りごと・参加制限：{participation or '未入力'}
・柔道整復師所見・補足：{clinical_note or '未入力'}

出力全体のルール:
・挨拶や前置きは不要です。最初から計画書の項目を出力してください。
・以下の10項目だけを、指定された見出しと順番で出力してください。
・入力されていない情報を創作しないでください。
・傷病名だけから症状や検査結果を推測しないでください。
・未評価、未実施、未入力と、異常なし、陰性を明確に区別してください。
・評価情報が不足している項目を異常なしと判断しないでください。
・Markdownのアスタリスクを使用しないでください。
・隅付き括弧は、指定された10項目の見出しだけに使用してください。
・見出しの名称と順番を変更しないでください。
・項目間に不要な空行を作らないでください。

【疼痛について】
20文字以内。NRS、疼痛部位、疼痛誘発動作、疼痛の性質を統合して記載してください。
疼痛情報がすべて未評価・未入力の場合は「疼痛評価情報なし」としてください。
【筋力について】
20文字以内。MMT評価で筋力低下ありとされた内容を反映してください。
すべて未評価の場合は「筋力評価情報なし」としてください。
すべて筋力低下なしの場合は「明らかな筋力低下なし」としてください。
【感覚異常について】
20文字以内。感覚検査の結果を反映してください。
すべて未評価の場合は「感覚評価情報なし」としてください。
すべて感覚異常なしの場合は「明らかな感覚異常なし」としてください。
【可動域について】
20文字以内。ROM制限の有無と制限因子を反映してください。
疼痛、筋性、軟部組織性、骨性の制限因子が選択されている場合は、最も重要な内容を簡潔に反映してください。
すべて未評価の場合は「可動域評価情報なし」としてください。
【短期目標】
100文字以内。疼痛、ROM、筋力、感覚、スペシャルテスト、生活上の困りごとを統合して作成してください。
入力から判断できない内容を追加しないでください。
【長期目標】
50文字以内。生活上の困りごと・参加制限の改善を中心に作成してください。
具体的な参加制限が未入力の場合は、入力された機能評価から判断できる範囲だけで作成してください。
【治療方針】
120文字以内。疼痛、ROM、筋力、感覚、スペシャルテスト、柔道整復師所見を統合して記載してください。
新しい診断名や入力されていない病態を追加しないでください。
【治療内容】
「①」「②」の番号付き箇条書きで、最大6行にしてください。
入力された評価結果と柔道整復師所見から判断できる範囲で作成してください。
具体的な治療内容を判断できる情報がない場合は、次の1行だけを出力してください。
①評価結果に基づき治療内容を検討
入力されていない具体的な運動名、物理療法、治療手技、回数、負荷量を勝手に追加しないでください。
【参加制限に対する具体的な対応方針】
200文字以内、簡潔な「です・ます調」で記載してください。
生活上の困りごと・参加制限を中心に作成し、適宜改行してください。ただし、空行は作らないでください。
参加制限が未入力の場合は、推測せず情報不足であることを明記してください。
【機能障害に対する具体的な対応方針】
200文字以内、簡潔な「です・ます調」で記載してください。
疼痛、ROM、筋力、感覚、スペシャルテストの結果を統合し、適宜改行してください。ただし、空行は作らないでください。
評価情報が不足している項目を異常なしと判断しないでください。"""
